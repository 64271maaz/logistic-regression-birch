import numpy as np
import matplotlib.pyplot as plt
from sklearn.datasets import make_blobs
from sklearn.cluster import Birch
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import silhouette_score

# 1. Generate synthetic dataset (unlabeled use hoga)
X, y_true = make_blobs(n_samples=1000, centers=4,
                       cluster_std=0.8, random_state=42)

# 2. Scale features
X_scaled = StandardScaler().fit_transform(X)

# 3. Train BIRCH model
birch = Birch(threshold=0.5, branching_factor=50, n_clusters=4)
labels = birch.fit_predict(X_scaled)

# 4. Evaluate
print("Number of clusters found:", len(np.unique(labels)))
print("Silhouette Score:", round(silhouette_score(X_scaled, labels), 4))
print("Cluster sizes:", np.bincount(labels))

# Visualization: BIRCH clusters and their centroids
plt.figure(figsize=(8, 6))
scatter = plt.scatter(X_scaled[:, 0], X_scaled[:, 1],
                      c=labels, cmap='viridis', s=20, alpha=0.7)

centers = birch.subcluster_centers_
plt.scatter(centers[:, 0], centers[:, 1], marker='X',
            s=200, c='red', edgecolor='black', label='Subcluster centers')

plt.title('BIRCH Clustering Result')
plt.xlabel('Feature 1 (scaled)')
plt.ylabel('Feature 2 (scaled)')
plt.colorbar(scatter, label='Cluster ID')
plt.legend()
plt.show()

